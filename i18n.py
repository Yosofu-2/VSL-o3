_current_lang = "en"  # default: English
_config_file = os.path.join(os.path.dirname(os.path.abspath(__file__)), ".lang_config")


def load_language():
    global _current_lang
    try:
        if os.path.exists(_config_file):
            with open(_config_file, "r", encoding="utf-8") as f:
                _current_lang = f.read().strip()
                if _current_lang not in ("zh", "en"):
                    _current_lang = "en"
    except Exception:
        _current_lang = "en"
    return _current_lang


def save_language(lang):
    global _current_lang
    _current_lang = lang
    try:
        with open(_config_file, "w", encoding="utf-8") as f:
            f.write(lang)
    except Exception:
        pass


def set_language(lang):
    global _current_lang
    _current_lang = lang
    save_language(lang)


def get_language():
    return _current_lang


def tr(text):
    """Translate English to Chinese if language is zh."""
    if _current_lang == "zh":
        return _translations.get(text, text)
    return text

# Load saved language on import
load_language()
